"""Storage contract used by the pipeline. Implementations: memory (tests/demo) and Postgres (Supabase)."""
from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal
from typing import Any, Protocol

from ..core.matching import CatalogIndex, MatchResult
from ..core.models import FlyerSource, NormalizedListing, ProductIdentity, RawBranch, StoreRecord
from ..vision.validator import ValidatedPromotion


@dataclass
class OfferWrite:
    changed: bool        # price differs from the previous observation
    created: bool


class Repository(Protocol):
    # stores & settings
    def list_stores(self, active_only: bool = True) -> list[StoreRecord]: ...
    def get_store(self, slug: str) -> StoreRecord | None: ...
    def upsert_store(self, data: dict[str, Any]) -> str: ...
    def latest_usd_lbp(self) -> Decimal: ...

    # runs
    def start_run(self, store_id: str, adapter_key: str, kind: str) -> int: ...
    def finish_run(self, run_id: int, status: str, stats: dict[str, Any], alerts: list[dict],
                   errors: list[dict], baseline: int | None) -> None: ...
    def recent_item_counts(self, store_id: str, kind: str, limit: int = 5) -> list[int]: ...
    def hours_since_last_run(self, store_id: str, kind: str) -> float | None: ...

    # catalogue
    def upsert_branches(self, store_id: str, branches: list[RawBranch]) -> dict[str, str]: ...
    def branch_map(self, store_id: str) -> dict[str, str]: ...
    def catalog_index(self) -> CatalogIndex: ...
    def create_canonical(self, ident: ProductIdentity, display_name: str, brand: str | None,
                         category_hint: str | None, image_url: str | None) -> str: ...
    def upsert_source_product(self, store_id: str, n: NormalizedListing, canonical_id: str | None,
                              m: MatchResult) -> str: ...
    def upsert_offer(self, source_product_id: str, canonical_id: str | None, store_id: str,
                     branch_id: str | None, n: NormalizedListing, run_id: int, source_kind: str) -> OfferWrite: ...
    def mark_unseen_stale(self, store_id: str, run_id: int) -> int: ...
    def reference_price_usd(self, canonical_id: str) -> Decimal | None: ...

    # flyers & promotions
    def flyer_exists(self, sha256: str) -> bool: ...
    def create_flyer(self, store_id: str, source: FlyerSource, sha256: str, mime: str | None,
                     run_id: int | None) -> str: ...
    def finish_flyer(self, flyer_id: str, status: str, page_count: int, extracted: int,
                     accepted: int, llm_calls: int, valid_from: Any, valid_until: Any, error: str | None) -> None: ...
    def upsert_promotion(self, store_id: str, vp: ValidatedPromotion, ident: ProductIdentity,
                         canonical_id: str | None, flyer_id: str | None, page: int | None,
                         dedupe_key: str) -> bool: ...
    def expire_promotions(self) -> int: ...
